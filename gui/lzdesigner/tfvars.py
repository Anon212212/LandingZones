"""Render a LandingZoneConfig as terraform.tfvars (HCL)."""

from __future__ import annotations

import json
from datetime import datetime, timezone

from . import __version__
from .model import LandingZoneConfig


def _hcl(value, indent: int = 0) -> str:
    pad = "  " * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(int(value)) if float(value).is_integer() else str(value)
    if value is None:
        return "null"
    if isinstance(value, str):
        return json.dumps(value)  # HCL string escaping is JSON-compatible
    if isinstance(value, (list, tuple)):
        if not value:
            return "[]"
        if all(not isinstance(v, (dict, list)) for v in value):
            return "[" + ", ".join(_hcl(v) for v in value) + "]"
        inner = ",\n".join(f"{pad}  {_hcl(v, indent + 1)}" for v in value)
        return "[\n" + inner + f"\n{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        width = max(len(_key(k)) for k in value)
        inner = "\n".join(f"{pad}  {_key(k).ljust(width)} = {_hcl(v, indent + 1)}" for k, v in value.items())
        return "{\n" + inner + f"\n{pad}}}"
    raise TypeError(f"unsupported value {value!r}")


def _key(k: str) -> str:
    return k if k.replace("_", "").replace("-", "").isalnum() and not k[0].isdigit() and "-" not in k else json.dumps(k)


SECTIONS: list[tuple[str, list[str]]] = [
    ("Organisation", ["org_prefix", "environment", "location", "owner", "cost_center", "tags"]),
    ("Subscriptions", ["subscription_id", "identity_subscription_id", "shared_services_subscription_id",
                       "production_subscription_id"]),
    ("Network", ["hub_address_space", "enable_nat_gateway", "nva_mgmt_source_cidrs"]),
    ("Spokes", ["spokes"]),
    ("Resilience", ["zones", "nva_zones", "enable_resource_locks"]),
    ("NVAs", ["nva_admin_username", "nva_admin_ssh_public_key", "nva_size", "nva_cpu_alert_threshold",
              "nva_encryption_at_host"]),
    ("Security", ["ddos_protection_plan_id", "bastion_sku"]),
    ("Identity (tier-0)", ["identity_regions", "dc_size", "dc_admin_username", "dc_image_sku",
                           "dc_data_disk_size_gb", "dc_hybrid_benefit", "identity_admin_source_cidrs",
                           "identity_allow_hub_bastion", "identity_dns_servers",
                           "identity_key_vault_allowed_ips", "identity_backup_storage_mode"]),
    ("Operations & cost", ["log_retention_days", "log_daily_quota_gb", "enable_flow_logs",
                           "flow_log_retention_days", "alert_email_addresses", "monthly_budget_amount"]),
]


def tfvars_values(cfg: LandingZoneConfig) -> dict:
    """Terraform variable name → value (designer-only fields excluded)."""
    values = {}
    for _, names in SECTIONS:
        for n in names:
            v = getattr(cfg, n)
            if n == "identity_regions":
                v = {r.key: {"location": r.location, "address_space": r.address_space, "dc_zones": r.dc_zones}
                     for r in cfg.identity_regions}
            if n == "spokes":
                v = {}
                for sp in cfg.spokes:
                    item = {"address_space": sp.address_space, "subscription": sp.subscription}
                    if sp.subnet_name:
                        item["subnet_name"] = sp.subnet_name
                    if sp.nsg_rules:
                        item["nsg_rules"] = [{
                            "name": r.name, "priority": int(r.priority), "direction": r.direction, "access": r.access,
                            "protocol": r.protocol, "source_address_prefixes": r.source_address_prefixes,
                            "destination_port_ranges": r.destination_port_ranges} for r in sp.nsg_rules]
                    v[sp.key] = item
            if n in ("ddos_protection_plan_id", "shared_services_subscription_id", "production_subscription_id") and not v:
                v = None
            values[n] = v
    return values


def render(cfg: LandingZoneConfig, frameworks_note: str = "") -> str:
    values = tfvars_values(cfg)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# ---------------------------------------------------------------------------",
        f"# Generated by Landing Zone Designer {__version__} on {stamp}",
        f"# Frameworks: {', '.join(cfg.frameworks)}{(' – ' + frameworks_note) if frameworks_note else ''}",
        "# Edit in the designer (gui/) rather than by hand to keep the guardrails.",
        "# ---------------------------------------------------------------------------",
    ]
    for title, names in SECTIONS:
        out.append("")
        out.append(f"# --- {title} " + "-" * max(3, 70 - len(title)))
        width = max(len(n) for n in names)
        for n in names:
            v = values[n]
            if v is None:
                continue
            out.append(f"{n.ljust(width)} = {_hcl(v)}")
    return "\n".join(out) + "\n"
